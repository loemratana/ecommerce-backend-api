-- Payments: one row per payment attempt for an order (a customer can retry or switch method),
-- created by PaymentService and driven by a PaymentGateway strategy (Stripe, cash on delivery).
--
-- IF [NOT] EXISTS everywhere: ddl-auto=update may already have created some of this.

-- The method the customer chose; cash-on-delivery orders skip PAID and are not expired.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_method VARCHAR(30);

CREATE TABLE IF NOT EXISTS payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version            BIGINT,
    order_id           BIGINT         NOT NULL REFERENCES orders (id),
    method             VARCHAR(30)    NOT NULL,
    status             VARCHAR(30)    NOT NULL,
    amount             NUMERIC(19, 2) NOT NULL,
    refunded_amount    NUMERIC(19, 2) NOT NULL DEFAULT 0,
    currency           VARCHAR(3)     NOT NULL,
    -- The gateway's id for this payment, e.g. a Stripe Checkout Session id
    provider_reference VARCHAR(255),
    -- Where to send the customer to pay (Stripe Checkout URL); null for cash on delivery
    redirect_url       VARCHAR(2048),
    failure_reason     VARCHAR(500),
    paid_at            TIMESTAMP,
    created_at         TIMESTAMP      NOT NULL,
    updated_at         TIMESTAMP      NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payment_order ON payments (order_id);
CREATE INDEX IF NOT EXISTS idx_payment_status ON payments (status);
CREATE UNIQUE INDEX IF NOT EXISTS uk_payment_provider_reference
    ON payments (method, provider_reference) WHERE provider_reference IS NOT NULL;

-- Gateways resend webhooks; an event id seen before is ignored.
CREATE TABLE IF NOT EXISTS processed_payment_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method       VARCHAR(30)  NOT NULL,
    event_id     VARCHAR(255) NOT NULL,
    processed_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_processed_payment_event UNIQUE (method, event_id)
);
