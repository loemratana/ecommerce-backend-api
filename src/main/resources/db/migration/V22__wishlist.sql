-- Wishlist: products a customer saved for later. One row per (user, product); the variant
-- (size/color) is only chosen when the item is moved to the cart.
--
-- IF NOT EXISTS everywhere: ddl-auto=update may already have created some of this.

CREATE TABLE IF NOT EXISTS wishlist_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id BIGINT    NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_wishlist_user_product UNIQUE (user_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_wishlist_item_user_id ON wishlist_items (user_id);
CREATE INDEX IF NOT EXISTS idx_wishlist_item_product_id ON wishlist_items (product_id);
