-- 1. Archive instead of delete: products and variants get a status. Archived ones stay for order,
--    return and stock history but are hidden from the shop and can't be bought.
-- 2. Returns: customers request returns of delivered orders; received items are restocked or
--    written off and the refund is recorded on the order.
--
-- IF [NOT] EXISTS everywhere: ddl-auto=update may already have created some of this.

-- ---- archive -------------------------------------------------------------------------------
ALTER TABLE products ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';
ALTER TABLE product_variants ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE';
CREATE INDEX IF NOT EXISTS idx_product_status ON products (status);

-- Color + size only has to be unique among ACTIVE variants, so a removed (archived) "Red / M"
-- doesn't block adding a new one.
DROP INDEX IF EXISTS uk_product_variant_color_size;
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM product_variants WHERE status = 'ACTIVE'
        GROUP BY prouduct_id, lower(trim(coalesce(color, ''))), coalesce(product_size_id, 0)
        HAVING count(*) > 1
    ) THEN
        RAISE NOTICE 'uk_product_variant_color_size not created: duplicate active color/size variants exist';
    ELSE
        CREATE UNIQUE INDEX uk_product_variant_color_size
            ON product_variants (prouduct_id, lower(trim(coalesce(color, ''))), coalesce(product_size_id, 0))
            WHERE status = 'ACTIVE';
    END IF;
END $$;

-- ---- orders: delivery date (starts the return period) and refunds ---------------------------
ALTER TABLE orders ADD COLUMN IF NOT EXISTS delivered_at TIMESTAMP;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS refunded_amount NUMERIC(19, 2) NOT NULL DEFAULT 0;
-- Best guess for orders delivered before this column existed: their last update.
UPDATE orders SET delivered_at = update_date WHERE status = 'DELIVERED' AND delivered_at IS NULL;

-- ---- returns -------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS return_requests (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(32)  NOT NULL,
    version       BIGINT,
    order_id      BIGINT       NOT NULL REFERENCES orders (id),
    user_id       BIGINT       NOT NULL REFERENCES users (id),
    status        VARCHAR(20)  NOT NULL,
    reason        VARCHAR(1000) NOT NULL,
    admin_note    VARCHAR(1000),
    refund_amount NUMERIC(19, 2),
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP    NOT NULL,
    received_at   TIMESTAMP,
    CONSTRAINT uk_return_number UNIQUE (return_number)
);
CREATE INDEX IF NOT EXISTS idx_return_order ON return_requests (order_id);
CREATE INDEX IF NOT EXISTS idx_return_user ON return_requests (user_id);
CREATE INDEX IF NOT EXISTS idx_return_status ON return_requests (status);

CREATE TABLE IF NOT EXISTS return_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_request_id BIGINT      NOT NULL REFERENCES return_requests (id) ON DELETE CASCADE,
    order_item_id     BIGINT      NOT NULL REFERENCES order_items (id),
    quantity          INTEGER     NOT NULL CHECK (quantity > 0),
    item_condition    VARCHAR(20)
);
CREATE INDEX IF NOT EXISTS idx_return_item_order_item ON return_items (order_item_id);
CREATE INDEX IF NOT EXISTS idx_return_item_request ON return_items (return_request_id);
